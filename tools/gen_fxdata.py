#!/usr/bin/env python3
"""Generate js/xl/fxdata.js from Korg's microKORG XL MIDI Implementation text.

Parses the "EFFECT PARAMETER STRUCTURE" section and the *T08-xx lookup
tables so the 17 effect types don't have to be transcribed by hand.

Usage: python3 tools/gen_fxdata.py docs/microKORG_XL_MIDIimp.txt > js/xl/fxdata.js
"""
import json
import re
import sys


def parse_tables(lines):
    """Return {'T08-02': ['0.01', ...]} for each *T08-xx lookup table."""
    tables = {}
    cur = None
    for line in lines:
        m = re.match(r'^ \*(T08-\d\d) :', line)
        if m:
            cur = m.group(1)
            tables[cur] = {}
            continue
        if cur is None:
            continue
        pairs = re.findall(r'(\d+):\s*(\S+)', line)
        if not pairs:
            if tables[cur] and not line.strip():
                cur = None
            continue
        for idx, val in pairs:
            tables[cur][int(idx)] = val
    out = {}
    for name, d in tables.items():
        out[name] = [d[i] for i in range(max(d) + 1)]
    return out


def parse_fmt(desc):
    desc = desc.strip()
    table = re.search(r'\*(T08-\d\d)', desc)
    if desc.startswith('0,1~99,100=Dry'):
        return {'k': 'drywet', 'min': 0, 'max': 100}
    m = re.match(r'^(\d+)~(\d+)=', desc)
    if table and m:
        unit = ''
        u = re.search(r'(msec|Hz|kHz|%)\s+\*', desc)
        if u:
            unit = u.group(1)
        return {'k': 'table', 't': table.group(1), 'min': int(m.group(1)),
                'max': int(m.group(2)), 'unit': unit}
    # enums: "0,1=Off,On" / "0~4=Saw,Squ,..." where RHS count matches range
    m = re.match(r'^(\d+)(?:,|~)(\d+)=(.+)$', desc)
    if m:
        lo, hi, rhs = int(m.group(1)), int(m.group(2)), m.group(3).strip()
        opts = [o.strip() for o in rhs.split(',')]
        if len(opts) == hi - lo + 1 and '~' not in rhs:
            return {'k': 'enum', 'o': opts}
    m = re.match(r'^64\+/-(\d+)=(.*)$', desc)
    if m:
        n = int(m.group(1))
        rhs = m.group(2)
        scale, dec, unit = 1, 0, ''
        if 'dB' in rhs and ('17.5' in rhs or '15' in rhs):
            scale, dec, unit = 0.5, 1, 'dB'
        elif 'degree' in rhs:
            scale, unit = 10, '°'
        elif 'cent' in rhs:
            scale, unit = 2, 'c'
        return {'k': 'range', 'min': 64 - n, 'max': 64 + n, 'bias': 64,
                'scale': scale, 'dec': dec, 'unit': unit}
    if desc.startswith('0~95=0.5'):
        return {'k': 'range', 'min': 0, 'max': 95, 'scale': 0.1, 'add': 0.5, 'dec': 1}
    if desc.startswith('0~94=1.0'):
        return {'k': 'range', 'min': 0, 'max': 94, 'scale': 0.5, 'add': 1, 'dec': 1, 'unit': 'kHz'}
    if desc.startswith('0~20=4~24'):
        return {'k': 'range', 'min': 0, 'max': 20, 'add': 4, 'unit': 'bit'}
    if desc.startswith('0~18=0,10'):
        return {'k': 'range', 'min': 0, 'max': 18, 'scale': 10, 'unit': '°'}
    m = re.match(r'^(\d+)~(\d+)=(\d+)~(\d+)\s*(%?)', desc)
    if m and int(m.group(1)) == int(m.group(3)):
        return {'k': 'range', 'min': int(m.group(1)), 'max': int(m.group(2)),
                'unit': m.group(5)}
    raise ValueError('Unrecognised effect value format: %r' % desc)


def parse_effects(lines):
    start = lines.index('EFFECT PARAMETER STRUCTURE')
    effects = [{'name': 'No Effect', 'params': []}]
    cur = None
    for line in lines[start + 1:]:
        if line.startswith(' *T08-'):
            break
        m = re.match(r'^(\d+)\s{2,}(\S.*)$', line)
        if m:
            cur = {'name': m.group(2).strip(), 'params': []}
            assert int(m.group(1)) == len(effects), line
            effects.append(cur)
            continue
        m = re.match(r'^\|\s+\+(\d+)\s+\|([^|]+)\|([^|]+)\|', line)
        if m and cur is not None:
            assert int(m.group(1)) == len(cur['params']), line
            cur['params'].append({'name': m.group(2).strip(), **parse_fmt(m.group(3))})
    return effects


def main():
    lines = open(sys.argv[1], encoding='ascii', errors='replace').read().replace('\r', '').split('\n')
    tables = parse_tables(lines)
    effects = parse_effects(lines)
    used = {p['t'] for e in effects for p in e['params'] if p['k'] == 'table'}
    missing = used - set(tables)
    if missing:
        raise SystemExit('missing tables: %s' % sorted(missing))
    print('// Generated by tools/gen_fxdata.py from docs/microKORG_XL_MIDIimp.txt. Do not edit.')
    print('export const FX_TABLES = %s;' % json.dumps({k: tables[k] for k in sorted(used)}))
    print('export const FX_TYPES = %s;' % json.dumps(effects, indent=1))


if __name__ == '__main__':
    main()
